/// <summary>The road trip. At the start of your turn, gain 1 energy and 2 Block for each turn so far this combat.</summary>
public class IdahoToJerseyAndBack() : DavidCard(3, CardType.Power, CardRarity.Rare, TargetType.Self)
{
    protected override IEnumerable<DynamicVar> CanonicalVars => [new PowerVar<IdahoToJerseyPower>(1), new EnergyVar(1)];

    protected override async Task OnPlay(PlayerChoiceContext ctx, CardPlay play)
    {
        await CommonActions.ApplySelf<IdahoToJerseyPower>(ctx, this);
    }

    protected override void OnUpgrade() => EnergyCost.UpgradeBy(-1);
}
