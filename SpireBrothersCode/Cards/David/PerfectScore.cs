namespace SpireBrothers.SpireBrothersCode.Cards.David;

/// <summary>Deal 16 damage. Exact: deal 8 more.</summary>
public class PerfectScore() : DavidCard(2, CardType.Attack, CardRarity.Uncommon, TargetType.AnyEnemy)
{
    public override IEnumerable<CardKeyword> CanonicalKeywords => [BrotherKeywords.Exact];
    protected override IEnumerable<DynamicVar> CanonicalVars => [new DamageVar(16, ValueProp.Move), new DynamicVar("ExactDamage", 8)];

    protected override async Task OnPlay(PlayerChoiceContext ctx, CardPlay play)
    {
        int exact = await Exact.Check(ctx, this);
        decimal damage = DynamicVars.Damage.BaseValue + exact * DynamicVars["ExactDamage"].BaseValue;
        await CommonActions.CardAttack(this, play, play.Target, damage, ValueProp.Move, vfx: "vfx/vfx_heavy_blunt").Execute(ctx);
    }

    protected override void OnUpgrade() => DynamicVars.Damage.UpgradeValueBy(4);
}
