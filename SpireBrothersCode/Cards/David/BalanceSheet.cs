/// <summary>Deal damage equal to your Block.</summary>
public class BalanceSheet() : DavidCard(1, CardType.Attack, CardRarity.Uncommon, TargetType.AnyEnemy)
{
    protected override IEnumerable<DynamicVar> CanonicalVars => [
        new CalculationBaseVar(0),
        new ExtraDamageVar(1),
        new CalculatedDamageVar(ValueProp.Move).WithMultiplier(CurrentBlock)
    ];

    private static decimal CurrentBlock(CardModel card, Creature? _) => card.Owner?.Creature?.Block ?? 0;

    protected override async Task OnPlay(PlayerChoiceContext ctx, CardPlay play)
    {
        await CommonActions.CardAttack(this, play, vfx: "vfx/vfx_heavy_blunt").Execute(ctx);
    }

    protected override void OnUpgrade() => EnergyCost.UpgradeBy(-1);
}
