/// <summary>ARK. At the start of your turn, deal 6 damage to ALL enemies.</summary>
public class DinoArmy() : DavidCard(3, CardType.Power, CardRarity.Rare, TargetType.Self)
{
    protected override IEnumerable<DynamicVar> CanonicalVars => [new PowerVar<DinoArmyPower>(6)];

    protected override async Task OnPlay(PlayerChoiceContext ctx, CardPlay play)
    {
        await CommonActions.ApplySelf<DinoArmyPower>(ctx, this);
    }

    protected override void OnUpgrade() => DynamicVars["DinoArmyPower"].UpgradeValueBy(3);
}
