/// <summary>Reggae. Deal 5 damage. If you played a Skill this turn, deal 5 more.</summary>
public class Riddim() : BrandiCard(1, CardType.Attack, CardRarity.Common, TargetType.AnyEnemy)
{
    protected override IEnumerable<DynamicVar> CanonicalVars => [
        new CalculationBaseVar(5),
        new ExtraDamageVar(5),
        new CalculatedDamageVar(ValueProp.Move).WithMultiplier(PlayedASkill)
    ];
    protected override bool ExtraGlow => PlayedThisTurn.Skills(Owner, CombatState) > 0;

    private static decimal PlayedASkill(CardModel card, Creature? _) =>
        PlayedThisTurn.Skills(card.Owner, card.CombatState) > 0 ? 1 : 0;

    protected override async Task OnPlay(PlayerChoiceContext ctx, CardPlay play)
    {
        await CommonActions.CardAttack(this, play, vfx: "vfx/vfx_attack_blunt").Execute(ctx);
    }

    protected override void OnUpgrade()
    {
        DynamicVars.CalculationBase.UpgradeValueBy(2);
        DynamicVars.ExtraDamage.UpgradeValueBy(2);
    }
}
