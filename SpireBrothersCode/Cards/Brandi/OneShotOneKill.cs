namespace SpireBrothers.SpireBrothersCode.Cards.Brandi;

/// <summary>Ancient (Dusty Tome). Shot attacks no longer spend your Aim. You can play only 1 Shot attack each turn.</summary>
public class OneShotOneKill() : BrandiCard(3, CardType.Power, CardRarity.Ancient, TargetType.Self)
{
    public override IEnumerable<CardKeyword> CanonicalKeywords => [BrotherKeywords.Shot];
    protected override IEnumerable<IHoverTip> ExtraHoverTips => [HoverTipFactory.FromPower<AimPower>()];

    protected override async Task OnPlay(PlayerChoiceContext ctx, CardPlay play)
    {
        await PowerCmd.Apply<OneShotOneKillPower>(ctx, Owner.Creature, 1, Owner.Creature, this);
    }

    protected override void OnUpgrade() => EnergyCost.UpgradeBy(-1);
}
