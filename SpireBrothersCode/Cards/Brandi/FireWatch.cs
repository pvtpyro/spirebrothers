namespace SpireBrothers.SpireBrothersCode.Cards.Brandi;

/// <summary>Army duty. Gain 8 Block. At the start of your next turn, apply 3 Ember to a random enemy.</summary>
public class FireWatch() : BrandiCard(1, CardType.Skill, CardRarity.Uncommon, TargetType.Self)
{
    public override bool GainsBlock => true;
    protected override IEnumerable<DynamicVar> CanonicalVars => [new BlockVar(8, ValueProp.Move), new DynamicVar("Ember", 3)];
    protected override IEnumerable<IHoverTip> ExtraHoverTips => [HoverTipFactory.FromPower<EmberPower>()];

    protected override async Task OnPlay(PlayerChoiceContext ctx, CardPlay play)
    {
        await CommonActions.CardBlock(this, play);
        await PowerCmd.Apply<FireWatchPower>(ctx, Owner.Creature, DynamicVars["Ember"].BaseValue, Owner.Creature, this);
    }

    protected override void OnUpgrade()
    {
        DynamicVars.Block.UpgradeValueBy(3);
        DynamicVars["Ember"].UpgradeValueBy(1);
    }
}
