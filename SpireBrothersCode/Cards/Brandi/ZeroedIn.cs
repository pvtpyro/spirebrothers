/// <summary>Sniper. Double your Aim. Exhaust. Upgrade: no longer Exhausts.</summary>
public class ZeroedIn() : BrandiCard(1, CardType.Skill, CardRarity.Uncommon, TargetType.Self)
{
    public override IEnumerable<CardKeyword> CanonicalKeywords => [CardKeyword.Exhaust];
    protected override IEnumerable<IHoverTip> ExtraHoverTips => [HoverTipFactory.FromPower<AimPower>()];
    protected override bool ExtraGlow => Aim.Count(Owner) > 0;

    protected override async Task OnPlay(PlayerChoiceContext ctx, CardPlay play)
    {
        await Aim.Gain(ctx, Owner, Aim.Count(Owner), this);
    }

    protected override void OnUpgrade() => RemoveKeyword(CardKeyword.Exhaust);
}
