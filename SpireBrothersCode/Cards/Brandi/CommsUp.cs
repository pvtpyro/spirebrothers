/// <summary>Signal. Whenever you apply Intel, gain 2 Block.</summary>
public class CommsUp() : BrandiCard(1, CardType.Power, CardRarity.Uncommon, TargetType.Self)
{
    protected override IEnumerable<DynamicVar> CanonicalVars => [new PowerVar<CommsUpPower>(2)];
    protected override IEnumerable<IHoverTip> ExtraHoverTips => [HoverTipFactory.FromPower<IntelPower>()];

    protected override async Task OnPlay(PlayerChoiceContext ctx, CardPlay play)
    {
        await CommonActions.ApplySelf<CommsUpPower>(ctx, this);
    }

    protected override void OnUpgrade() => DynamicVars["CommsUpPower"].UpgradeValueBy(1);
}
