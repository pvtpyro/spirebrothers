/// <summary>30+ years of web dev. The first time you play your 3rd card each turn, draw 1 card. Upgrade: Innate.</summary>
public class Since1993() : BrandiCard(1, CardType.Power, CardRarity.Rare, TargetType.Self)
{
    protected override IEnumerable<DynamicVar> CanonicalVars => [new PowerVar<Since1993Power>(1)];

    protected override async Task OnPlay(PlayerChoiceContext ctx, CardPlay play)
    {
        await CommonActions.ApplySelf<Since1993Power>(ctx, this);
    }

    protected override void OnUpgrade() => AddKeyword(CardKeyword.Innate);
}
