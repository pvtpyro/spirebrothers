/// <summary>Metal. Deal 10 damage. If it's the last card in your hand, deal double.</summary>
public class Breakdown() : BrandiCard(1, CardType.Attack, CardRarity.Uncommon, TargetType.AnyEnemy)
{
    protected override IEnumerable<DynamicVar> CanonicalVars => [
        new CalculationBaseVar(10),
        new ExtraDamageVar(10),
        new CalculatedDamageVar(ValueProp.Move).WithMultiplier((card, _) => LastInHand(card) ? 1 : 0)
    ];
    protected override bool ExtraGlow => LastInHand(this);

    private static bool LastInHand(CardModel card) =>
        card.Owner?.PlayerCombatState != null && !PileType.Hand.GetPile(card.Owner).Cards.Any(c => c != card);

    protected override async Task OnPlay(PlayerChoiceContext ctx, CardPlay play)
    {
        await CommonActions.CardAttack(this, play, vfx: "vfx/vfx_heavy_blunt").Execute(ctx);
    }

    protected override void OnUpgrade()
    {
        DynamicVars.CalculationBase.UpgradeValueBy(4);
        DynamicVars.ExtraDamage.UpgradeValueBy(4);
    }
}
