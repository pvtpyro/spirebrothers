/// <summary>Her other nickname. At the start of your turn, gain 3 Static.</summary>
public class Sparky() : BrandiCard(1, CardType.Power, CardRarity.Rare, TargetType.Self)
{
    protected override IEnumerable<DynamicVar> CanonicalVars => [new PowerVar<SparkyPower>(3)];
    protected override IEnumerable<IHoverTip> ExtraHoverTips => [HoverTipFactory.FromPower<StaticPower>()];

    protected override async Task OnPlay(PlayerChoiceContext ctx, CardPlay play)
    {
        await CommonActions.ApplySelf<SparkyPower>(ctx, this);
    }

    protected override void OnUpgrade() => DynamicVars["SparkyPower"].UpgradeValueBy(2);
}
