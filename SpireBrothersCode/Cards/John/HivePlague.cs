/// <summary>Hive Scum. At the start of your turn, apply 2 Toxin to ALL enemies.</summary>
public class HivePlague() : JohnCard(2, CardType.Power, CardRarity.Rare, TargetType.Self)
{
    protected override IEnumerable<DynamicVar> CanonicalVars => [new PowerVar<HivePlaguePower>(2)];
    protected override IEnumerable<IHoverTip> ExtraHoverTips => [HoverTipFactory.FromPower<ToxinPower>()];

    protected override async Task OnPlay(PlayerChoiceContext ctx, CardPlay play)
    {
        await CommonActions.ApplySelf<HivePlaguePower>(ctx, this);
    }

    protected override void OnUpgrade() => DynamicVars["HivePlaguePower"].UpgradeValueBy(1);
}
