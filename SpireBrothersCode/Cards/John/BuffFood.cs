namespace SpireBrothers.SpireBrothersCode.Cards.John;

/// <summary>WoW raid feasts. ALL players gain 2 Strength this turn (vanilla Flex Potion's power). Exhaust.</summary>
public class BuffFood() : JohnCard(1, CardType.Skill, CardRarity.Uncommon, TargetType.Self)
{
    public override IEnumerable<CardKeyword> CanonicalKeywords => [CardKeyword.Exhaust];
    protected override IEnumerable<DynamicVar> CanonicalVars => [new DynamicVar("Strength", 2)];

    protected override async Task OnPlay(PlayerChoiceContext ctx, CardPlay play)
    {
        await PowerCmd.Apply<FlexPotionPower>(ctx, AllPlayers, DynamicVars["Strength"].BaseValue, Owner.Creature, this);
    }

    protected override void OnUpgrade() => DynamicVars["Strength"].UpgradeValueBy(1);
}
