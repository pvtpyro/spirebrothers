namespace SpireBrothers.SpireBrothersCode.Cards.John;

/// <summary>WoW (pull one mob at a time). Deal 9 damage. If it's the only enemy, deal 4 more.</summary>
public class SinglePull() : JohnCard(1, CardType.Attack, CardRarity.Common, TargetType.AnyEnemy)
{
    protected override IEnumerable<DynamicVar> CanonicalVars => [
        new CalculationBaseVar(9),
        new ExtraDamageVar(4),
        new CalculatedDamageVar(ValueProp.Move).WithMultiplier(Alone)
    ];
    protected override bool ExtraGlow => CombatState?.HittableEnemies.Count == 1;

    private static decimal Alone(CardModel card, Creature? _) => card.CombatState?.HittableEnemies.Count == 1 ? 1 : 0;

    protected override async Task OnPlay(PlayerChoiceContext ctx, CardPlay play)
    {
        await CommonActions.CardAttack(this, play, vfx: "vfx/vfx_attack_slash").Execute(ctx);
    }

    protected override void OnUpgrade()
    {
        DynamicVars.CalculationBase.UpgradeValueBy(3);
        DynamicVars.ExtraDamage.UpgradeValueBy(1);
    }
}
