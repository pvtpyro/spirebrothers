/// <summary>His dog. Deal damage equal to the Mastiff's Bite. Then the Mastiff bites that enemy too.</summary>
public class PackTactics() : HuffmanCard(1, CardType.Attack, CardRarity.Uncommon, TargetType.AnyEnemy)
{
    public override IEnumerable<CardKeyword> CanonicalKeywords => [BrotherKeywords.Mastiff];
    protected override IEnumerable<DynamicVar> CanonicalVars => [
        new CalculationBaseVar(0),
        new ExtraDamageVar(1),
        new CalculatedDamageVar(ValueProp.Move).WithMultiplier(Bite)
    ];

    private static decimal Bite(CardModel card, Creature? _) => Mastiff.Bite(card.Owner);

    protected override async Task OnPlay(PlayerChoiceContext ctx, CardPlay play)
    {
        await CommonActions.CardAttack(this, play, vfx: "vfx/vfx_attack_slash").Execute(ctx);
        if (play.Target is { IsAlive: true }) await Mastiff.Attack(ctx, Owner, play.Target);
    }

    protected override void OnUpgrade() => DynamicVars.CalculationBase.UpgradeValueBy(4);
}
