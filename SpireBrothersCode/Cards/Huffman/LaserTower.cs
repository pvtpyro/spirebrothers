/// <summary>Total Annihilation. Deal 7 damage. Build 2: deal it again.</summary>
public class LaserTower() : HuffmanCard(1, CardType.Attack, CardRarity.Common, TargetType.AnyEnemy)
{
    protected override int BuildCost => 2;
    public override IEnumerable<CardKeyword> CanonicalKeywords => [BrotherKeywords.Build];
    protected override IEnumerable<DynamicVar> CanonicalVars => [new DamageVar(7, ValueProp.Move)];

    protected override async Task OnPlay(PlayerChoiceContext ctx, CardPlay play)
    {
        await CommonActions.CardAttack(this, play, vfx: "vfx/vfx_attack_slash").Execute(ctx);
        if (play.Target is { IsAlive: true } && await Build(ctx))
            await CommonActions.CardAttack(this, play, vfx: "vfx/vfx_attack_slash").Execute(ctx);
    }

    protected override void OnUpgrade() => DynamicVars.Damage.UpgradeValueBy(3);
}
