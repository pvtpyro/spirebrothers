/// <summary>Cars. Discard your hand, then draw that many cards plus 1. Upgrade: costs 0.</summary>
public class OilChange() : DanielCard(1, CardType.Skill, CardRarity.Uncommon, TargetType.Self)
{
    public override IEnumerable<CardKeyword> CanonicalKeywords => [BrotherKeywords.Hands];
    protected override IEnumerable<DynamicVar> CanonicalVars => [new CardsVar(1)];

    protected override async Task OnPlay(PlayerChoiceContext ctx, CardPlay play)
    {
        var hand = PileType.Hand.GetPile(Owner).Cards.ToList();
        await CardCmd.DiscardAndDraw(ctx, hand, hand.Count + DynamicVars.Cards.IntValue);
    }

    protected override void OnUpgrade() => EnergyCost.UpgradeBy(-1);
}
