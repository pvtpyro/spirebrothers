/// <summary>Helldivers 2. Whenever you play a Stratagem, gain 1 energy and draw 1 card. Upgrade: costs 1.</summary>
public class ForDemocracy() : DanielCard(2, CardType.Power, CardRarity.Rare, TargetType.Self)
{
    protected override IEnumerable<DynamicVar> CanonicalVars => [new PowerVar<ForDemocracyPower>(1), new EnergyVar(1), new CardsVar(1)];

    protected override async Task OnPlay(PlayerChoiceContext ctx, CardPlay play)
    {
        await CommonActions.ApplySelf<ForDemocracyPower>(ctx, this);
    }

    protected override void OnUpgrade() => EnergyCost.UpgradeBy(-1);
}
