/// <summary>Titanfall. Pilot (Stim): draw 2. Titan (Overcore): gain 1 Energy. Exhaust.</summary>
public class StimShot() : DannyCard(0, CardType.Skill, CardRarity.Common, TargetType.Self)
{
    public override IEnumerable<CardKeyword> CanonicalKeywords => [CardKeyword.Exhaust];
    protected override IEnumerable<DynamicVar> CanonicalVars => [new CardsVar(2), new EnergyVar(1)];

    protected override Task OnPilot(PlayerChoiceContext ctx, CardPlay play) => Draw(ctx, DynamicVars.Cards.BaseValue);

    protected override Task OnTitan(PlayerChoiceContext ctx, CardPlay play) => PlayerCmd.GainEnergy(DynamicVars.Energy.IntValue, Owner);

    protected override void OnUpgrade()
    {
        DynamicVars.Cards.UpgradeValueBy(1);
        DynamicVars.Energy.UpgradeValueBy(1);
    }
}
