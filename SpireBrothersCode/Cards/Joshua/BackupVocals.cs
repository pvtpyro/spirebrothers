/// <summary>Vocals. Whenever you play a Song card, gain 2 Block.</summary>
public class BackupVocals() : JoshuaCard(1, CardType.Power, CardRarity.Uncommon, TargetType.Self)
{
    protected override IEnumerable<DynamicVar> CanonicalVars => [new PowerVar<BackupVocalsPower>(2)];

    protected override async Task OnPlay(PlayerChoiceContext ctx, CardPlay play)
    {
        await CommonActions.ApplySelf<BackupVocalsPower>(ctx, this);
    }

    protected override void OnUpgrade() => DynamicVars["BackupVocalsPower"].UpgradeValueBy(1);
}
