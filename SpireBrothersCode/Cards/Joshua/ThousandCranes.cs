/// <summary>Japan (senbazuru, folded for recovery). The first time ANY player would die this combat, they heal 30% of their Max HP instead.</summary>
public class ThousandCranes() : JoshuaCard(3, CardType.Power, CardRarity.Rare, TargetType.Self)
{
    protected override IEnumerable<DynamicVar> CanonicalVars => [new PowerVar<ThousandCranesPower>(30)];

    protected override async Task OnPlay(PlayerChoiceContext ctx, CardPlay play)
    {
        await CommonActions.ApplySelf<ThousandCranesPower>(ctx, this);
    }

    protected override void OnUpgrade() => EnergyCost.UpgradeBy(-1);
}
