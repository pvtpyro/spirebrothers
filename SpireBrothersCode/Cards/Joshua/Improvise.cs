/// <summary>Music. Add a random Song card to your hand. It costs 0 this turn. Upgrade: add 2.</summary>
public class Improvise() : JoshuaCard(0, CardType.Skill, CardRarity.Uncommon, TargetType.Self)
{
    protected override IEnumerable<DynamicVar> CanonicalVars => [new CardsVar(1)];

    protected override async Task OnPlay(PlayerChoiceContext ctx, CardPlay play)
    {
        await Verses.AddRandomSongs(Owner, DynamicVars.Cards.IntValue, freeThisTurn: true);
    }

    protected override void OnUpgrade() => DynamicVars.Cards.UpgradeValueBy(1);
}
