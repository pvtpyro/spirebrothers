/// <summary>Piano / guitar. Whenever you play a Song card, deal 4 damage to ALL enemies.</summary>
public class Virtuoso() : JoshuaCard(3, CardType.Power, CardRarity.Rare, TargetType.Self)
{
    protected override IEnumerable<DynamicVar> CanonicalVars => [new PowerVar<VirtuosoPower>(4)];

    protected override async Task OnPlay(PlayerChoiceContext ctx, CardPlay play)
    {
        await CommonActions.ApplySelf<VirtuosoPower>(ctx, this);
    }

    protected override void OnUpgrade() => EnergyCost.UpgradeBy(-1);
}
