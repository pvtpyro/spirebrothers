/// <summary>Age of Empires. Deal 12 damage. Imperial Age: deal 8 more.</summary>
public class Paladin() : TimCard(2, CardType.Attack, CardRarity.Uncommon, TargetType.AnyEnemy)
{
    protected override int? AgeBonusAt => Ages.Imperial;
    public override IEnumerable<CardKeyword> CanonicalKeywords => [BrotherKeywords.Age];
    protected override IEnumerable<DynamicVar> CanonicalVars => [
        new CalculationBaseVar(12),
        new ExtraDamageVar(8),
        new CalculatedDamageVar(ValueProp.Move).WithMultiplier(Imperial)
    ];

    private static decimal Imperial(CardModel card, Creature? _) => Ages.Get(card.Owner) >= Ages.Imperial ? 1 : 0;

    protected override async Task OnPlay(PlayerChoiceContext ctx, CardPlay play)
    {
        await CommonActions.CardAttack(this, play, vfx: "vfx/vfx_heavy_blunt").Execute(ctx);
    }

    protected override void OnUpgrade() => DynamicVars.CalculationBase.UpgradeValueBy(4);
}
