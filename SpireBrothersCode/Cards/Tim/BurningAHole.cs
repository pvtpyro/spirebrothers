/// <summary>Money burns a hole in his pocket. Whenever you spend Gold, deal 1 damage to ALL enemies per 10 Gold spent.</summary>
public class BurningAHole() : TimCard(1, CardType.Power, CardRarity.Uncommon, TargetType.Self)
{
    protected override IEnumerable<DynamicVar> CanonicalVars => [new PowerVar<BurningAHolePower>(1)];

    protected override async Task OnPlay(PlayerChoiceContext ctx, CardPlay play)
    {
        await CommonActions.ApplySelf<BurningAHolePower>(ctx, this);
    }

    protected override void OnUpgrade() => DynamicVars["BurningAHolePower"].UpgradeValueBy(1);
}
