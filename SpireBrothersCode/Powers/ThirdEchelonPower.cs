namespace SpireBrothers.SpireBrothersCode.Powers;

/// <summary>Tim's Third Echelon (Splinter Cell). At the start of your turn, apply Amount Weak to ALL enemies.</summary>
public class ThirdEchelonPower : BrothersPower
{
    public override PowerType Type => PowerType.Buff;
    public override PowerStackType StackType => PowerStackType.Counter;

    public override async Task AfterPlayerTurnStart(PlayerChoiceContext choiceContext, Player player)
    {
        if (player.Creature != Owner || CombatState == null || !CombatState.HittableEnemies.Any()) return;
        Flash();
        await PowerCmd.Apply<WeakPower>(choiceContext, CombatState.HittableEnemies, Amount, Owner, null);
    }
}
