namespace SpireBrothers.SpireBrothersCode.Powers;

/// <summary>WoW. At the start of John's turn, ALL players gain Amount Strength this turn (vanilla Flex Potion's power).</summary>
public class RaidLeaderPower : BrothersPower
{
    public override PowerType Type => PowerType.Buff;
    public override PowerStackType StackType => PowerStackType.Counter;

    public override async Task AfterPlayerTurnStart(PlayerChoiceContext choiceContext, Player player)
    {
        if (player.Creature != Owner || Owner.CombatState is not { } combat) return;
        Flash();
        var raid = combat.Players.Where(p => p.Creature.IsAlive).Select(p => p.Creature).ToList();
        await PowerCmd.Apply<FlexPotionPower>(choiceContext, raid, Amount, Owner, null);
    }
}
