/// <summary>Sniper. Whenever Brandi ends her turn without playing an Attack, she gains Amount Aim.</summary>
public class HideSitePower : BrothersPower
{
    public override PowerType Type => PowerType.Buff;
    public override PowerStackType StackType => PowerStackType.Counter;

    public override async Task BeforeSideTurnEnd(PlayerChoiceContext choiceContext, CombatSide side, IEnumerable<Creature> participants)
    {
        if (!participants.Contains(Owner) || Owner.Player is not { } player) return;
        if (PlayedThisTurn.Attacks(player, Owner.CombatState) > 0) return;
        Flash();
        await Aim.Gain(choiceContext, player, Amount, null);
    }
}
