/// <summary>Disc Priest. Whenever Brandi plays an Attack, the player with the lowest HP gains Amount Block.</summary>
public class AtonementPower : BrothersPower
{
    public override PowerType Type => PowerType.Buff;
    public override PowerStackType StackType => PowerStackType.Counter;

    public override async Task AfterCardPlayed(PlayerChoiceContext choiceContext, CardPlay cardPlay)
    {
        if (cardPlay.Card.Owner?.Creature != Owner || cardPlay.Card.Type != CardType.Attack || Owner.Player is not { } player) return;
        Flash();
        await LowestHp.Block(player, Amount);
    }
}
