namespace SpireBrothers.SpireBrothersCode.Powers;

/// <summary>Army. Whenever Brandi loses HP, she gains Amount Aim.</summary>
public class EmbraceTheSuckPower : BrothersPower
{
    public override PowerType Type => PowerType.Buff;
    public override PowerStackType StackType => PowerStackType.Counter;

    public override async Task AfterDamageReceived(PlayerChoiceContext choiceContext, Creature target, DamageResult result, ValueProp props, Creature? dealer, CardModel? cardSource)
    {
        if (target != Owner || result.UnblockedDamage <= 0 || Owner.Player is not { } player || !Owner.IsAlive) return;
        Flash();
        await Aim.Gain(choiceContext, player, Amount, null);
    }
}
