namespace SpireBrothers.SpireBrothersCode.Powers;

/// <summary>Total Annihilation. At the start of Huffman's turn, gain Amount Metal and 2 Block per stack.</summary>
public class SolarCollectorPower : BrothersPower
{
    public const int BlockPerStack = 2;
    public override PowerType Type => PowerType.Buff;
    public override PowerStackType StackType => PowerStackType.Counter;

    public override async Task AfterPlayerTurnStart(PlayerChoiceContext choiceContext, Player player)
    {
        if (player.Creature != Owner) return;
        Flash();
        await Metal.Gain(choiceContext, player, Amount, null);
        await CreatureCmd.GainBlock(Owner, Amount * BlockPerStack, ValueProp.Unpowered, null);
    }
}
