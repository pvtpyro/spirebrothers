namespace SpireBrothers.SpireBrothersCode.Powers;

/// <summary>AE2. Whenever one of Huffman's cards is Exhausted, gain Amount Metal.</summary>
public class MeNetworkPower : BrothersPower
{
    public override PowerType Type => PowerType.Buff;
    public override PowerStackType StackType => PowerStackType.Counter;

    public override async Task AfterCardExhausted(PlayerChoiceContext choiceContext, CardModel card, bool causedByEthereal)
    {
        if (card.Owner?.Creature != Owner || Owner.Player is not { } player) return;
        Flash();
        await Metal.Gain(choiceContext, player, Amount, null);
    }
}
